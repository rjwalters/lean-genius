#!/usr/bin/env npx tsx
/**
 * Emit the Cloudflare Pages `_redirects` file from the tracked OQ slug redirect
 * map (issue #39825, epic #39821).
 *
 * Source of truth: `src/data/proofs/redirects.json`
 *   { "$comment": "...", "redirects": { "<old-slug>": "<new-slug>", ... } }
 *
 * Outputs (both under the gitignored, build-generated public tree):
 *   - `public/_redirects`               one `301` rule per entry, applied by
 *                                       Cloudflare before its SPA fallback.
 *   - `public/data/proofs/redirects.json`  the raw map, for optional client use.
 *
 * The foundation PR ships an empty map, so this normally writes a header-only
 * `_redirects`. The mass migration (#39828) fills the map in.
 *
 * Usage: tsx scripts/gallery/build-redirects.ts
 */

import * as fs from 'fs'
import * as path from 'path'
import { fileURLToPath } from 'url'

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)

const REDIRECTS_SOURCE = path.join(__dirname, '../../src/data/proofs/redirects.json')
const PUBLIC_DIR = path.join(__dirname, '../../public')
const PUBLIC_REDIRECTS = path.join(PUBLIC_DIR, '_redirects')
const PUBLIC_MAP = path.join(PUBLIC_DIR, 'data/proofs/redirects.json')

/** A basic slug shape guard: kebab-case path segment, no spaces or slashes. */
const SLUG_RE = /^[a-z0-9]+(?:-[a-z0-9]+)*$/i

interface RedirectsFile {
  redirects?: Record<string, string>
  [meta: string]: unknown
}

/**
 * Read the tracked redirect map, dropping `$`-prefixed metadata keys and
 * validating each old→new pair. Returns a plain slug→slug object.
 */
export function loadRedirects(sourcePath: string = REDIRECTS_SOURCE): Record<string, string> {
  if (!fs.existsSync(sourcePath)) return {}
  const raw = JSON.parse(fs.readFileSync(sourcePath, 'utf8')) as RedirectsFile
  const map = raw.redirects ?? {}
  const out: Record<string, string> = {}
  for (const [from, to] of Object.entries(map)) {
    if (from.startsWith('$')) continue // metadata, not a slug
    if (typeof to !== 'string') {
      throw new Error(`redirects.json: value for "${from}" must be a string, got ${typeof to}`)
    }
    if (!SLUG_RE.test(from)) throw new Error(`redirects.json: invalid old slug "${from}"`)
    if (!SLUG_RE.test(to)) throw new Error(`redirects.json: invalid new slug "${to}" (for "${from}")`)
    if (from === to) throw new Error(`redirects.json: "${from}" redirects to itself`)
    out[from] = to
  }
  return out
}

/**
 * Render a Cloudflare Pages `_redirects` body from a slug→slug map. One rule per
 * line: `/proof/<old>  /proof/<new>  301`. Rules are sorted for a stable,
 * churn-free diff.
 */
export function renderRedirectsFile(map: Record<string, string>): string {
  const header = [
    '# Auto-generated by scripts/gallery/build-redirects.ts — DO NOT EDIT.',
    '# Source of truth: src/data/proofs/redirects.json (issue #39825).',
    '# One 301 per retired OQ slug; Cloudflare applies these before the SPA fallback.',
    '',
  ]
  const lines = Object.keys(map)
    .sort()
    .map((from) => `/proof/${from}  /proof/${map[from]}  301`)
  return header.concat(lines).join('\n') + '\n'
}

function main(): void {
  const map = loadRedirects()
  const count = Object.keys(map).length

  fs.mkdirSync(path.dirname(PUBLIC_MAP), { recursive: true })
  fs.writeFileSync(PUBLIC_REDIRECTS, renderRedirectsFile(map))
  fs.writeFileSync(PUBLIC_MAP, JSON.stringify(map))

  console.log(
    `🔀 Generated public/_redirects (${count} redirect${count === 1 ? '' : 's'}) ` +
      `and public/data/proofs/redirects.json`
  )
}

// Run only when invoked directly (not when imported by a test).
if (process.argv[1] && path.resolve(process.argv[1]) === __filename) {
  main()
}
