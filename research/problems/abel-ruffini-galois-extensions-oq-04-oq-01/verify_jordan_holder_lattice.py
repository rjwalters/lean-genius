"""
Durable verification cert for abel-ruffini-galois-extensions-oq-04-oq-01 (S1 ORIENT).

OQ-04-OQ-01: "Can `JordanHolderLattice (Subgroup G)` be contributed upstream to
Mathlib?" The parent file AbelRuffiniGaloisExtensionsOQ04.lean already proves the
instance locally (0 sorries) via `IsMaxNorm` (maximal *normal* subgroup) with the
two non-trivial axioms:

  (A1) sup_eq_of_isMaximal:
       IsMaxNorm x z -> IsMaxNorm y z -> x != y  ==>  x ⊔ y = z
  (A2) isMaximal_inf_left_of_isMaximal_sup:
       IsMaxNorm x (x⊔y) -> IsMaxNorm y (x⊔y)    ==>  IsMaxNorm (x⊓y) x

This cert independently checks A1 and A2 on concrete finite groups by brute-force
enumeration of the full subgroup lattice and the maximal-normal relation. It is a
regression oracle for the Lean instance and evidence that the mathematics is
correct on examples (the upstreaming question is one of PACKAGING, not provability
-- see state.md: Mathlib's TODO is a global-instance-diamond design concern).

`IsMaxNorm H K`  :=  H < K, H normal in K, and no subgroup M normal in K with
                    H < M < K  (i.e. H is a maximal proper normal subgroup of K).
`H ⊔ K`          :=  subgroup generated by H ∪ K.
`H ⊓ K`          :=  H ∩ K.

No external deps (pure stdlib). Groups are concrete permutation groups.
"""

from itertools import product as iproduct


# ---- permutation group machinery (perms as tuples on {0..n-1}) ----
def compose(p, q):
    # (p∘q)(i) = p(q(i))
    return tuple(p[q[i]] for i in range(len(p)))


def inverse(p):
    inv = [0] * len(p)
    for i, pi in enumerate(p):
        inv[pi] = i
    return tuple(inv)


def closure(gens, n):
    ident = tuple(range(n))
    elems = {ident}
    frontier = list(gens) + [ident]
    elems.update(gens)
    changed = True
    while changed:
        changed = False
        cur = list(elems)
        for a in cur:
            for b in cur:
                c = compose(a, b)
                if c not in elems:
                    elems.add(c)
                    changed = True
    return frozenset(elems)


def all_subgroups(G, n):
    """All subgroups of G (G a frozenset of perms). Brute force over generating
    sets is too slow; instead grow subgroups by closure of element subsets,
    deduplicated. For |G| <= 8 the cyclic-closure approach below suffices."""
    ident = tuple(range(n))
    elemlist = sorted(G)
    subs = set()
    # every subgroup is the closure of some subset of <=2 generators for |G|<=8
    subs.add(frozenset([ident]))
    for a in elemlist:
        subs.add(closure([a], n))
    for i, a in enumerate(elemlist):
        for b in elemlist[i + 1:]:
            subs.add(closure([a, b], n))
    subs.add(G)
    return sorted(subs, key=lambda s: (len(s), sorted(s)))


def is_normal_in(H, K, n):
    """H normal in K (assumes H <= K). For k in K, h in H: k h k^-1 in H."""
    for k in K:
        kinv = inverse(k)
        for h in H:
            if compose(compose(k, h), kinv) not in H:
                return False
    return True


def join(H, K, n):
    return closure(list(H) + list(K), n)


def meet(H, K):
    return H & K


def is_max_norm(H, K, subs, n):
    """H is a maximal proper normal subgroup of K."""
    if not (H < K):
        return False
    if not is_normal_in(H, K, n):
        return False
    for M in subs:
        if H < M < K and is_normal_in(M, K, n):
            return False
    return True


def check_group(name, gens, n):
    G = closure(gens, n)
    subs = all_subgroups(G, n)
    # restrict the "subs" set to actual subgroups of G
    subs = [s for s in subs if s <= G]

    maxnorm_in_G = [H for H in subs if is_max_norm(H, G, subs, n)]

    a1_checks = a1_ok = 0
    # A1: any two distinct maximal-normal subgroups of any z join to z
    for z in subs:
        mn = [H for H in subs if is_max_norm(H, z, subs, n)]
        for i in range(len(mn)):
            for j in range(len(mn)):
                if i == j:
                    continue
                x, y = mn[i], mn[j]
                a1_checks += 1
                if join(x, y, n) == z:
                    a1_ok += 1

    a2_checks = a2_ok = 0
    # A2: if x,y both maximal-normal in x⊔y, then x⊓y maximal-normal in x
    for x in subs:
        for y in subs:
            xy = join(x, y, n)
            if is_max_norm(x, xy, subs, n) and is_max_norm(y, xy, subs, n):
                a2_checks += 1
                if is_max_norm(meet(x, y), x, subs, n):
                    a2_ok += 1

    ok = (a1_ok == a1_checks) and (a2_ok == a2_checks)
    print(f"[{'PASS' if ok else 'FAIL'}] {name}: |G|={len(G)}, "
          f"#subgroups={len(subs)}, #maxnorm(G)={len(maxnorm_in_G)} | "
          f"A1 {a1_ok}/{a1_checks}, A2 {a2_ok}/{a2_checks}")
    return ok


def map_subgroup(H, phi):
    """Image phi(H) = {phi(h) : h in H} as a frozenset. For a homomorphism phi
    this is automatically a subgroup of the codomain."""
    return frozenset(phi[h] for h in H)


def is_homomorphism(phi, G, n_dom):
    """Check phi : G -> codomain respects composition on all pairs."""
    for a in G:
        for b in G:
            if phi[compose(a, b)] != compose(phi[a], phi[b]):
                return False
    return True


def check_map_obstruction():
    """Durable witness for the *map* half of the Mathlib TODO.

    Mathlib master/v4.26.0 already provide the generic carrier
    `RelSeries.map (p) (f : r.Hom s)` (Order/RelSeries.lean:372) which pushes a
    series along a *relation-preserving* map `f`. The JordanHolder TODO asks for
    "an API for mapping composition series across homomorphisms". The naive
    candidate -- push a CompositionSeries of `Subgroup G` along `Subgroup.map phi`
    -- does NOT instantiate `RelSeries.Hom` for the `IsMaxNorm` relation, because
    `IsMaxNorm` (maximal *normal* covering) is not stable under images with
    nontrivial kernel.

    Concrete obstruction: G = C4 = <g>, kernel N = <g^2> (order 2), quotient map
    phi : C4 -> C4/N =~ C2. The composition series {e} <| <g^2> <| C4 has the
    maximal-normal covering {e} <| <g^2>. But phi({e}) = phi(<g^2>) = {e}
    (since <g^2> = ker phi), so the image step {e} <| {e} is NOT a covering
    (not even strict). Hence `Subgroup.map phi` fails the `r.Hom s` step law and
    `RelSeries.map` cannot be applied. The map API must therefore restrict phi
    (e.g. injective) or route quotient steps through the second isomorphism
    theorem -- it is not the trivial `RelSeries.map (Subgroup.map phi)`.
    """
    n = 4
    g = (1, 2, 3, 0)                      # 4-cycle generates C4 on {0,1,2,3}
    G = closure([g], n)
    subs = [s for s in all_subgroups(G, n) if s <= G]
    ident = tuple(range(n))
    g2 = compose(g, g)
    N = closure([g2], n)                  # <g^2>, order 2 = ker phi
    triv = frozenset([ident])

    # phi : C4 -> C2 (C2 realized on {0,1}); phi(g^k) = (1,0)^k.
    c2_id, c2_swap = (0, 1), (1, 0)
    phi = {}
    cur = ident
    img = c2_id
    for _ in range(len(G)):
        phi[cur] = img
        cur = compose(cur, g)
        img = compose(img, c2_swap)

    hom_ok = is_homomorphism(phi, G, n)
    cover_ok = is_max_norm(triv, N, subs, n)          # {e} <| <g^2> in C4
    phi_triv = map_subgroup(triv, phi)
    phi_N = map_subgroup(N, phi)
    collapses = (phi_triv == phi_N)                    # image step is non-strict
    # The image is not a covering: phi(triv) is not maximal-normal in phi(N).
    not_a_cover = (phi_triv == phi_N)                  # equal => not H < K

    ok = hom_ok and cover_ok and collapses and not_a_cover
    print(f"[{'PASS' if ok else 'FAIL'}] map-obstruction (C4 -->phi C2): "
          f"phi hom={hom_ok}, "
          f"source cover {{e}}<|<g^2>={cover_ok}, "
          f"image collapses phi({{e}})==phi(<g^2>)={collapses} "
          f"==> Subgroup.map phi is NOT an IsMaxNorm RelSeries.Hom")
    return ok


