#!/usr/bin/env python3
"""Goal #48 stage 1: proof-logged re-solve of the 36 leaves of h1_81494a6ef36d3ec9.

Each leaf CNF is regenerated byte-identically with cube_verdict.cube_bytes (sha checked
against the banked cube_sha256), then solved by CaDiCaL 3.0.1 with native LRAT output.
Receipts: <out>/receipts.jsonl (one line per leaf), never overwritten.
"""
import concurrent.futures as cf, hashlib, json, subprocess, sys, time, resource, os
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "phase_b_h1_verdict_cloud_20260921"))
import cube_verdict  # noqa: E402

CASE = Path("/Volumes/Stripe/lean-genius/artifacts/erdos85-sat49/h1-cube-pass4-20260926/h1_81494a6ef36d3ec9")
OUT = Path(sys.argv[1] if len(sys.argv) > 1 else "/Volumes/Stripe/lean-genius/artifacts/erdos85-sat49/h1-cert-pilot-20261001")
WORKERS = int(os.environ.get("WORKERS", "12"))
BINARY = os.environ.get("LRAT_BINARY", "true")
CADICAL = "/opt/homebrew/bin/cadical"

def sha(p): 
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 22), b""): h.update(b)
    return h.hexdigest()

results = json.loads((CASE / "run-adaptive/results.json").read_text())
base = cube_verdict.read_cnf(CASE / "run-adaptive/base.cnf")
assert sha(CASE / "run-adaptive/base.cnf") == results["base_sha256"]
leaves = [n for n in results["nodes"].values() if n["kind"] == "leaf"]
assert len(leaves) == 36
only = set(int(x) for x in os.environ.get("ONLY", "").split(",") if x)
if only: leaves = [n for n in leaves if n["id"] in only]
leaves.sort(key=lambda n: -n["crosscheck"]["elapsed_seconds"])
done = set()
rec_path = OUT / "receipts.jsonl"
if rec_path.exists():
    done = {json.loads(l)["node"] for l in rec_path.read_text().splitlines() if l.strip()}

def run(n):
    d = OUT / f"node-{n['id']:05d}"; d.mkdir(parents=True, exist_ok=True)
    cnf = d / "cube.cnf"
    assignment = {abs(l): int(l > 0) for l in n["literals"]}
    cnf.write_bytes(cube_verdict.cube_bytes(*base, assignment))
    csha = sha(cnf)
    if csha != n["cube_sha256"]:
        return {"node": n["id"], "status": "CUBE_SHA_MISMATCH", "got": csha, "want": n["cube_sha256"]}
    proof = d / "proof.lrat"
    cmd = [CADICAL, "-t", "86400", "--lrat=true", f"--binary={BINARY}", str(cnf), str(proof)]
    t0 = time.time()
    with open(d / "cadical.log", "wb") as log:
        p = subprocess.Popen(cmd, stdout=log, stderr=subprocess.STDOUT)
        _, status, ru = os.wait4(p.pid, 0)
    rc = os.waitstatus_to_exitcode(status)
    el = time.time() - t0
    return {"node": n["id"], "literals": n["literals"], "cube_sha256": csha, "command": cmd,
            "returncode": rc, "verdict": {20: "UNSAT", 10: "SAT"}.get(rc, "UNKNOWN"),
            "wall_seconds": el, "cpu_seconds": ru.ru_utime + ru.ru_stime, "maxrss_bytes": ru.ru_maxrss,
            "lrat_bytes": proof.stat().st_size if proof.exists() else None,
            "lrat_binary": BINARY == "true",
            "prior_kissat_seconds": n["primary"]["elapsed_seconds"],
            "prior_cadical_seconds": n["crosscheck"]["elapsed_seconds"],
            "finished_utc": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())}

OUT.mkdir(parents=True, exist_ok=True)
todo = [n for n in leaves if n["id"] not in done]
print(f"{len(todo)} leaves to solve, {WORKERS} workers", flush=True)
with cf.ThreadPoolExecutor(WORKERS) as ex, open(rec_path, "a") as rec:
    # as_completed: a receipt lands when its leaf finishes, not behind slower leaves (#48 crash lesson)
    for fut in cf.as_completed([ex.submit(run, n) for n in todo]):
        r = fut.result()
        rec.write(json.dumps(r) + "\n"); rec.flush()
        print(r["node"], r.get("verdict", r["status"] if "status" in r else "?"), round(r.get("wall_seconds", 0)), r.get("lrat_bytes"), flush=True)
