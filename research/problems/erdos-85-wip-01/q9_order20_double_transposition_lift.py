#!/usr/bin/env python3
"""Exact double-transposition lift model for q=9 order-20x4 shadows.

Every transitive subgroup of S4 contains a double transposition.  Normalize
a preimage of (01)(23) to use identity maps 0->1 and 2->3, with closing
twists alpha and beta.  The four block-triple parallel classes form two
orbits and are generated by four permutations satisfying explicit
alpha/beta intertwining laws.  Enumerating the twist-class pairs therefore
tests a necessary symmetry of every remaining component action.
"""

from __future__ import annotations

import argparse
import hashlib
import subprocess
import sys
from itertools import combinations
from pathlib import Path

import networkx as nx
import z3

from q9_order20_c4_lift import EXPECTED_SHA256, ORDINALS, component

OPEN_PAIRS = {4: (), 6: (), 7: ()}
ROOT_GAUGE_PAIRS = {4: ((5, 5),), 6: ((0, 0),), 7: ()}


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("census", type=Path)
    parser.add_argument("--ordinal", type=int, choices=ORDINALS, required=True)
    parser.add_argument("--alpha-class", type=int)
    parser.add_argument("--beta-class", type=int)
    parser.add_argument("--list-pairs", action="store_true")
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--decided", action="store_true")
    parser.add_argument("--timeout", type=int, default=300)
    parser.add_argument("--root-gauge", action="store_true")
    args = parser.parse_args()
    raw = args.census.read_bytes()
    assert hashlib.sha256(raw).hexdigest() == EXPECTED_SHA256
    base = component(raw, args.ordinal)
    automorphisms = sorted(
        tuple(mapping[v] for v in range(20))
        for mapping in nx.algorithms.isomorphism.GraphMatcher(base, base).isomorphisms_iter()
    )

    def compose(left, right):
        return tuple(left[right[v]] for v in range(20))

    def inverse(permutation):
        result = [0] * 20
        for source, target in enumerate(permutation):
            result[target] = source
        return tuple(result)

    def cycle_type(permutation):
        unseen = set(range(20))
        lengths = []
        while unseen:
            start = min(unseen)
            current = start
            length = 0
            while current in unseen:
                unseen.remove(current)
                current = permutation[current]
                length += 1
            lengths.append(length)
        return tuple(sorted(lengths))

    unseen = set(automorphisms)
    classes = []
    while unseen:
        representative = min(unseen)
        conjugates = {
            compose(compose(element, representative), inverse(element))
            for element in automorphisms
        }
        unseen -= conjugates
        classes.append((representative, len(conjugates)))
    classes.sort()
    admissible_pairs = [
        (a, b)
        for a, (alpha, _) in enumerate(classes)
        for b, (beta, _) in enumerate(classes)
        if cycle_type(alpha) == cycle_type(beta)
    ]
    if args.list_pairs:
        print(
            f"ordinal={args.ordinal}",
            f"automorphism_order={len(automorphisms)}",
            f"twist_classes={len(classes)}",
            f"admissible_pairs={admissible_pairs}",
        )
        return
    if args.all or args.decided:
        if args.alpha_class is not None or args.beta_class is not None:
            raise SystemExit("suite modes cannot be combined with a class selector")
        cases = [
            pair for pair in admissible_pairs
            if not args.decided or pair not in OPEN_PAIRS[args.ordinal]
        ]
        for alpha_class, beta_class in cases:
            command = [
                sys.executable, str(Path(__file__).resolve()), str(args.census),
                "--ordinal", str(args.ordinal),
                "--alpha-class", str(alpha_class),
                "--beta-class", str(beta_class),
                "--timeout", str(args.timeout),
            ]
            if (alpha_class, beta_class) in ROOT_GAUGE_PAIRS[args.ordinal]:
                command.append("--root-gauge")
            process = subprocess.run(
                command,
                text=True, capture_output=True,
            )
            if process.returncode != 0 or "result=unsat" not in process.stdout:
                sys.stdout.write(process.stdout)
                sys.stderr.write(process.stderr)
                raise RuntimeError(f"incomplete twist pair {(alpha_class, beta_class)}")
            print(f"completed_twist_pair={alpha_class},{beta_class}", flush=True)
        print(
            f"excluded_double_transposition_pairs ordinal={args.ordinal}",
            f"twist_pairs={len(cases)}",
            f"open_pairs={OPEN_PAIRS[args.ordinal] if args.decided else ()}",
        )
        return
    pair = (args.alpha_class, args.beta_class)
    if None in pair or pair not in admissible_pairs:
        raise SystemExit(f"class pair must be one of {admissible_pairs}")
    alpha, alpha_size = classes[args.alpha_class]
    beta, beta_size = classes[args.beta_class]
    alpha_inverse, beta_inverse = inverse(alpha), inverse(beta)

    solver = z3.Solver()
    matrices = {
        name: [[z3.Bool(f"{name}_{x}_{y}") for y in range(20)] for x in range(20)]
        for name in ("f", "g", "h", "k")
    }
    f, g, h, k = (matrices[name] for name in ("f", "g", "h", "k"))
    for name, matrix in matrices.items():
        for row in matrix:
            solver.add(z3.PbEq([(entry, 1) for entry in row], 1))
        for y in range(20):
            solver.add(z3.PbEq([(matrix[x][y], 1) for x in range(20)], 1))
        target_twist = alpha if name == "f" else beta
        for x in range(20):
            for y in range(20):
                solver.add(matrix[alpha[x]][target_twist[y]] == matrix[x][y])
    if args.root_gauge:
        alpha_centralizer = [
            element for element in automorphisms
            if compose(element, alpha) == compose(alpha, element)
        ]
        beta_centralizer = [
            element for element in automorphisms
            if compose(element, beta) == compose(beta, element)
        ]
        assert {element[0] for element in alpha_centralizer} == set(range(20))
        assert {element[0] for element in beta_centralizer} == set(range(20))
        # Residual coordinate changes by the two centralizers send
        # g -> b g a^-1.  Taking a=id and choosing b makes g(0)=0.
        solver.add(g[0][0])

    contribution = {}

    def put(triple, pair_blocks, left, right, value):
        contribution[triple, pair_blocks, left, right] = value

    for x in range(20):
        for y in range(20):
            # Seed A: (x,f(x),g(x)) on 012.
            put((0, 1, 2), (0, 1), x, y, f[x][y])
            put((0, 1, 2), (0, 2), x, y, g[x][y])
            # Its image: (alpha(f(t)),t,g(t)) on 013.
            put((0, 1, 3), (0, 1), x, y, f[y][alpha_inverse[x]])
            put((0, 1, 3), (1, 3), x, y, g[x][y])
            # Seed B: (x,h(x),k(x)) on 023.
            put((0, 2, 3), (0, 2), x, y, h[x][y])
            put((0, 2, 3), (0, 3), x, y, k[x][y])
            # Its image: (t,beta(k(t)),h(t)) on 123.
            put((1, 2, 3), (1, 2), x, y, k[x][beta_inverse[y]])
            put((1, 2, 3), (1, 3), x, y, h[x][y])

    for left in range(20):
        for right in range(20):
            put((0, 1, 2), (1, 2), left, right,
                z3.Or(*[z3.And(f[x][left], g[x][right]) for x in range(20)]))
            put((0, 1, 3), (0, 3), left, right,
                z3.Or(*[z3.And(f[x][alpha_inverse[left]], g[x][right]) for x in range(20)]))
            put((0, 2, 3), (2, 3), left, right,
                z3.Or(*[z3.And(h[x][left], k[x][right]) for x in range(20)]))
            put((1, 2, 3), (2, 3), left, right,
                z3.Or(*[z3.And(k[x][beta_inverse[left]], h[x][right]) for x in range(20)]))

    triples = tuple(combinations(range(4), 3))
    edge = {}
    for block_pair in combinations(range(4), 2):
        support = [triple for triple in triples if set(block_pair) <= set(triple)]
        for left in range(20):
            for right in range(20):
                terms = [contribution[t, block_pair, left, right] for t in support]
                solver.add(z3.PbLe([(term, 1) for term in terms], 1))
                value = z3.Bool(f"edge_{block_pair[0]}_{left}_{block_pair[1]}_{right}")
                solver.add(value == z3.Or(*terms))
                edge[block_pair, left, right] = value

    def adjacency(left, right):
        lb, lx = divmod(left, 20)
        rb, rx = divmod(right, 20)
        if lb == rb:
            return z3.BoolVal(base.has_edge(lx, rx))
        if lb > rb:
            lb, rb, lx, rx = rb, lb, rx, lx
        return edge[(lb, rb), lx, rx]

    for left, right in combinations(range(80), 2):
        terms = []
        for center in range(80):
            if center in (left, right):
                continue
            one, two = adjacency(left, center), adjacency(right, center)
            if not z3.is_false(one) and not z3.is_false(two):
                terms.append(z3.And(one, two))
        shadow_edge = left // 20 == right // 20 and base.has_edge(left % 20, right % 20)
        solver.add(z3.PbLe([(term, 1) for term in terms], 0 if shadow_edge else 1))

    print(
        f"ordinal={args.ordinal}", f"alpha_class={args.alpha_class}",
        f"beta_class={args.beta_class}", f"class_sizes={alpha_size},{beta_size}",
        f"assertions={len(solver.assertions())}", flush=True,
    )
    goal = z3.Goal()
    goal.add(*solver.assertions())
    cnf = z3.Then("simplify", "card2bv", "tseitin-cnf")(goal)
    assert len(cnf) == 1
    process = subprocess.run(
        ["kissat", "--quiet", f"--time={args.timeout}"],
        input=cnf[0].dimacs(), text=True, capture_output=True,
    )
    result = {10: "sat", 20: "unsat"}.get(process.returncode, "unknown")
    print(f"result={result}")


if __name__ == "__main__":
    main()
